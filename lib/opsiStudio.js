export function ambilKonfigurasiJenisKue(kode) {
  const target = (kode || "cake").toLowerCase();
  for (let i = 0; i < JENIS_KUE_STUDIO.length; i++) {
    if (JENIS_KUE_STUDIO[i].kode === target) {
      return JENIS_KUE_STUDIO[i];
    }
  }
  return JENIS_KUE_STUDIO[0];
}

export function normalisasiKodeJenisKue(nilai) {
  const v = String(nilai || "").trim().toLowerCase();
  if (v === "cupcake") return "cupcake";
  if (v === "tart" || v === "kue pie" || v === "pie") return "tart";
  if (v === "donut" || v === "donat") return "donut";
  if (v === "cookies" || v === "cookie") return "cookies";
  return "cake";
}

export function cariGrupBerdasarkanNama(daftarGrup, daftarNama) {
  if (!Array.isArray(daftarGrup) || !Array.isArray(daftarNama)) return null;
  for (let n = 0; n < daftarNama.length; n++) {
    const target = daftarNama[n].trim().toLowerCase();
    for (let i = 0; i < daftarGrup.length; i++) {
      if ((daftarGrup[i].nama || "").trim().toLowerCase() === target) {
        return daftarGrup[i];
      }
    }
  }
  return null;
}

export function cariGrupStep(daftarGrup, kodeJenis, peranStep) {
  const kode = normalisasiKodeJenisKue(kodeJenis);
  const peta = NAMA_GRUP_PER_PERAN[kode] || NAMA_GRUP_PER_PERAN.cake;
  const namaTarget = peta[peranStep];

  if (namaTarget) {
    const ketemu = cariGrupBerdasarkanNama(daftarGrup, namaTarget);
    if (ketemu) return ketemu;
  }

  if (peranStep === "jenis") {
    for (let i = 0; i < daftarGrup.length; i++) {
      if (daftarGrup[i].peran_dashboard === "jenis") return daftarGrup[i];
    }
  }

  if (kode !== "cake") {
    const fallbackCake = NAMA_GRUP_PER_PERAN.cake[peranStep];
    if (fallbackCake && (peranStep === "ukuran" || peranStep === "rasa" || peranStep === "dekorasi")) {
      const ketemuFallback = cariGrupBerdasarkanNama(daftarGrup, fallbackCake);
      if (ketemuFallback) return ketemuFallback;
    }
    return null;
  }

  if (peranStep === "ukuran") {
    return daftarGrup.find((g) => g.peran_visual === "ukuran") || null;
  }
  if (peranStep === "bentuk") {
    return daftarGrup.find((g) => g.peran_visual === "bentuk") || null;
  }
  if (peranStep === "rasa") {
    return daftarGrup.find((g) => g.peran_dashboard === "terlaris" || g.peran_visual === "badan") || null;
  }
  if (peranStep === "krim") {
    return daftarGrup.find((g) => g.peran_visual === "krim") || null;
  }
  if (peranStep === "dekorasi") {
    return daftarGrup.find((g) => g.peran_visual === "topping") || null;
  }
  if (peranStep === "stiker") {
    return daftarGrup.find((g) => g.peran_visual === "stiker") || null;
  }

  return null;
}

export function ambilGrupUntukJenisKue(daftarGrup, kodeJenis) {
  const konfig = ambilKonfigurasiJenisKue(kodeJenis);
  const hasil = [];
  const sudahAda = new Set();

  for (let s = 0; s < konfig.langkah.length; s++) {
    const step = konfig.langkah[s];
    for (let gIdx = 0; gIdx < step.grupNama.length; gIdx++) {
      const grup = cariGrupBerdasarkanNama(daftarGrup, [step.grupNama[gIdx]]);
      if (grup && !sudahAda.has(grup.id)) {
        sudahAda.add(grup.id);
        hasil.push({
          grup,
          langkah: step,
        });
      }
    }
  }

  return hasil;
}

export function deteksiJenisKueDariPilihan(daftarPilihan, opsiMap, grupMap, desainJson) {
  if (desainJson && desainJson.itemType) {
    return normalisasiKodeJenisKue(desainJson.itemType);
  }

  if (Array.isArray(daftarPilihan)) {
    for (let i = 0; i < daftarPilihan.length; i++) {
      const p = daftarPilihan[i];
      if (!p) continue;
      const optId = Number(typeof p === "object" ? p.id_item : p);
      const opt = opsiMap ? opsiMap.get(optId) : null;
      if (!opt) continue;
      const grp = grupMap ? grupMap.get(opt.id_grup) : null;
      const namaGrup = (grp?.nama || "").trim().toLowerCase();
      if (grp?.peran_dashboard === "jenis" || namaGrup === "jenis kue") {
        const kv = (opt.kode_visual || "").trim().toLowerCase();
        if (kv === "cupcake" || kv === "tart" || kv === "donut" || kv === "cookies" || kv === "cake") {
          return kv;
        }
        const nm = (opt.nama || "").trim().toLowerCase();
        if (nm.includes("cupcake")) return "cupcake";
        if (nm.includes("pie") || nm.includes("tart")) return "tart";
        if (nm.includes("donat") || nm.includes("donut")) return "donut";
        if (nm.includes("cookie")) return "cookies";
      }
      if (namaGrup === "porsi cupcake" || namaGrup === "rasa muffin" || namaGrup === "topping & krim") {
        return "cupcake";
      }
      if (namaGrup === "ukuran tart" || namaGrup === "rasa custard" || namaGrup === "topping buah") {
        return "tart";
      }
      if (namaGrup === "jumlah donat" || namaGrup === "rasa adonan" || namaGrup === "glaze & topping") {
        return "donut";
      }
      if (namaGrup === "jumlah cookies" || namaGrup === "varian rasa" || namaGrup === "topping & extra") {
        return "cookies";
      }
    }
  }

  return "cake";
}
